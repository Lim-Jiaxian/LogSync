-- LogSync schema (PostgreSQL). Safe to run on every start: every statement is IF NOT EXISTS.
-- js/server.js runs this file at startup, inside a transaction holding an advisory lock.
-- Timestamps are timestamptz (stored in UTC); the API formats them in Singapore time.

CREATE TABLE IF NOT EXISTS stations (
  id       integer PRIMARY KEY,
  division integer NOT NULL,
  name     text    NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  user_id        integer PRIMARY KEY,       -- replace with pseudonymous Singpass ref
  station_id     integer NOT NULL REFERENCES stations(id),
  username       text    NOT NULL UNIQUE,
  password       text,                      -- bcrypt hash; plaintext from seed.sql is hashed on first login
  role           text    NOT NULL DEFAULT 'FF' CHECK (role IN ('FF','SC','IC')),
  rota           integer NOT NULL CHECK (rota BETWEEN 1 AND 3),
  created_at     timestamptz NOT NULL DEFAULT now(),
  email          text,
  contact_number text
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,              -- sha256 of the bearer token; the token itself is never stored
  user_id    integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS appliances (
  callsign   text    PRIMARY KEY,
  station_id integer NOT NULL REFERENCES stations(id),
  type       text    NOT NULL               -- PL, LF, FMV, FB... not exhaustive, so no CHECK
);

CREATE TABLE IF NOT EXISTS equipment (
  equipment_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial_number text UNIQUE,                -- nullable: NA allowed
  name          text    NOT NULL,
  station_id    integer NOT NULL REFERENCES stations(id),
  appliance     text    REFERENCES appliances(callsign),
  status        text    NOT NULL CHECK (status IN
                ('ON_APPLIANCE','STORE','SERVICING','LOANED_OUT','MISSING','OTHER')),
  notes         text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CHECK ((status = 'ON_APPLIANCE') = (appliance IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS equipment_station ON equipment(station_id);

CREATE TABLE IF NOT EXISTS equipment_log (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id integer NOT NULL REFERENCES equipment(equipment_id),
  from_status  text,                        -- NULL when the item is first registered
  to_status    text    NOT NULL,
  changed_by   integer NOT NULL REFERENCES users(user_id),
  changed_at   timestamptz NOT NULL DEFAULT now(),
  note         text
);
CREATE INDEX IF NOT EXISTS equipment_log_equipment ON equipment_log(equipment_id);

CREATE TABLE IF NOT EXISTS checklist_items (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appliance     text    NOT NULL REFERENCES appliances(callsign),
  locker        text,                       -- 'Locker 2'
  kit           text,                       -- 'Power Saw, Petrol Driven'; NULL = standalone item
  label         text    NOT NULL,
  what_to_check text,
  expected_qty  integer NOT NULL DEFAULT 1,
  sort_order    integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS checklist_items_appliance ON checklist_items(appliance);

CREATE TABLE IF NOT EXISTS hoto_records (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appliance    text    NOT NULL REFERENCES appliances(callsign),
  rota         integer NOT NULL,            -- rota taking over
  completed_by integer NOT NULL REFERENCES users(user_id),
  completed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS service_requests (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id      integer NOT NULL REFERENCES equipment(equipment_id),
  requested_by      integer NOT NULL REFERENCES users(user_id),
  fault_description text    NOT NULL,
  status            text    NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED','CLOSED')),
  submitted_at      timestamptz NOT NULL DEFAULT now(),
  closed_at         timestamptz,            -- set when the item leaves SERVICING
  serial_number     text,
  material_number   text,
  fixed_asset_id    text,
  ats_id            text,
  nsf_id            text,
  sto_number        text,
  is_number         text,
  pv_fault          bytea,
  l_d               bytea,
  pv_fault_type     text,
  l_d_type          text
);
-- At most one open request per item, enforced by the database even under concurrent submits.
CREATE UNIQUE INDEX IF NOT EXISTS service_requests_one_open
  ON service_requests(equipment_id) WHERE status = 'SUBMITTED';

CREATE TABLE IF NOT EXISTS hoto_results (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id          integer NOT NULL REFERENCES hoto_records(id) ON DELETE CASCADE,
  item_id            integer NOT NULL REFERENCES checklist_items(id),
  equipment_id       integer REFERENCES equipment(equipment_id),
  result             text    NOT NULL CHECK (result IN ('OK','MISSING','FAULTY','QTY_MISMATCH')),
  note               text,
  service_request_id integer REFERENCES service_requests(id)
);
CREATE INDEX IF NOT EXISTS hoto_results_record ON hoto_results(record_id);
